def timeline():
    segs = [dict(id=i, a=a, b=b, st=st, rows=r) for i, a, b, st, r in SEGS]
    sfx = [['yazi_vurus', 1.45, 0], ['yazi_vurus', 5.55, 0], ['gecis', 7.45, 0], ['gecis', 10.12, 0], ['yazi_vurus', 13.9, -2]]
    for bn in BANNERS: sfx.append(['gecis', bn['a'] - .05, 0])
    for s in segs:
        sfx += [['card', s['a'] - .05, -2], ['stamp_dan', s['st'], 0]] + [['pop', r, -6] for r in s['rows']]
    sfx += [['gecis', OUTRO['a'] - .05, 0], ['yazi_vurus', OUTRO['a'] + .05, -2]] + [['pop', it[1], -3] for it in OUTRO['items']]
