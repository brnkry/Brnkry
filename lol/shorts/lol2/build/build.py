BG = 'scale=-2:1920,crop=1080:1920:(iw-1080)/2:0,gblur=sigma=28,eq=brightness=-0.18:saturation=1.1'

def vf(p):
    a, b, m, ss, q = p
    if m == 'P':
        s, x, y = q
        return f'split[a][b];[a]{BG}[bg];[b]crop={s}:{s}:{x}:{y},scale=1080:1080:flags=lanczos[fg];[bg][fg]overlay=0:{PY}'
    if m == 'C':
        x, dk = q
        return f'crop=506:900:{x}:0,scale=1080:1920:flags=lanczos,eq=brightness=-{dk}'
    if m == 'W':
        return f'split[a][b];[a]{BG}[bg];[b]scale=1080:-2:flags=lanczos[fg];[bg][fg]overlay=0:{PY}+236'
    return f'trim=end_frame=1,tpad=stop_mode=clone:stop_duration=30,crop=iw:900:0:0,{BG}'

def base(only=None):
    parts = []
    for i, p in enumerate(PLAN):
        o = f'{OUT}/p{i:02d}.mp4'; parts.append(o)
        if only and i not in only: continue
        n = round(p[1] * 30) - round(p[0] * 30)
        f = f'[0:v]{vf(p)},fps=30,tpad=stop_mode=clone:stop_duration=2,setsar=1[v]'
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-ss', str(p[3]), '-i', SRC, '-filter_complex', f, '-map', '[v]', '-frames:v', str(n),
                        '-an', '-c:v', 'libx264', '-preset', 'veryfast', '-crf', '16', '-pix_fmt', 'yuv420p', o], check=True)
        print('part', i, n, flush=True)
    open(f'{OUT}/list.txt', 'w').writelines(f"file '{x}'\n" for x in parts)
    subprocess.run(['ffmpeg', '-v', 'error', '-y', '-f', 'concat', '-safe', '0', '-i', f'{OUT}/list.txt', '-c', 'copy', f'{OUT}/base.mp4'], check=True)

def timeline():
    cuts = [p[0] for p in PLAN[1:]]
    open('timeline.js', 'w').write('// generated by build.py\nconst PLAN=' + json.dumps([[p[0], p[1], p[2]] for p in PLAN]) + ';\nconst CUTS=' + json.dumps(cuts) + f';\nconst END={END},PY={PY};\n')

def mix():
    subprocess.run(['node', 'render.js', 'info'], check=True); ev = json.load(open('sfx.json'))
    G = {'whoosh': -20, 'impact': -15, 'stamp_dan': -10, 'yazi_vurus': -15, 'card': -17, 'pop': -19, 'click': -14}
    inp = ['-i', '../ses/vo.mp3', '-stream_loop', '-1', '-i', '../../../sett/ses/muzik.mp3']
    fc = [f'[0]aresample=44100,aformat=channel_layouts=stereo,volume=4dB,apad=whole_dur={END},asplit[vo][sc]',
          f'[1]aresample=44100,aformat=channel_layouts=stereo,atrim=0:{END},volume=-15dB,afade=t=in:d=0.3,afade=t=out:st={END - 0.6}:d=0.6[m0]',
          '[m0][sc]sidechaincompress=threshold=0.02:ratio=6:attack=15:release=400[m]']; lab = ['[vo]', '[m]']
    for i, (n, t, g) in enumerate(ev):
        inp += ['-i', f'../ses/{n}.wav']
        fc.append(f'[{i + 2}]aresample=44100,aformat=channel_layouts=stereo,volume={G[n] + g}dB,adelay={int(t * 1000)}:all=1[s{i}]'); lab.append(f'[s{i}]')
    fc.append(''.join(lab) + f'amix=inputs={len(lab)}:normalize=0:duration=first,atrim=0:{END},loudnorm=I=-14:TP=-1.5:LRA=11[o]')
    subprocess.run(['ffmpeg', '-v', 'error', '-y'] + inp + ['-filter_complex', ';'.join(fc), '-map', '[o]', '-ar', '48000', f'{OUT}/mix.wav'], check=True)
    print('mix ok')

def check():  # first, middle and last source frame of every segment, to catch scene cuts and bad crops
    os.makedirs(f'{OUT}/chk', exist_ok=True)
    for i, p in enumerate(PLAN):
        d = p[1] - p[0]
        for k, t in enumerate([0.02, d / 2, d - 0.12]):
            subprocess.run(['ffmpeg', '-v', 'error', '-y', '-ss', str(t), '-i', f'{OUT}/p{i:02d}.mp4', '-frames:v', '1', '-vf', 'scale=270:480', f'{OUT}/chk/{i:02d}_{k}.png'], check=True)

