"""Sezon 2027 Short (9:16): base video + mix.
usage: python3 build.py base | mix
Sources: B = official New Dawn video, A = Season 2027 dev video (720p, subtitles burned in at the bottom),
         P:name = gameplay clips from the patch video (scratchpad/patch/norm).
Modes: G    full-height 9:16 crop at x        BL   blurred, darkened full cover (cards on top)
       C    cinematic crop 506x900 at x (subtitles left out)
       CARD A clip as a 16:9 card in the middle over a blurred copy of itself"""
import subprocess, sys, json, os
S = '/tmp/claude-0/-home-user-Brnkry/65f4241b-0184-50ef-a7c2-5a98c9618836/scratchpad'
SRC = {'B': S + '/lol2/official.mp4', 'A': S + '/ocak/sezon2027.mp4'}
OUT = S + '/s27/out'; os.makedirs(OUT, exist_ok=True)
D = 0.2; END = 48.9; CY = 640  # card top
CUTS = {'B': [59.79, 63.13, 66.08, 72.67, 75.17, 78.25, 81.21, 88.17, 94.46, 97.42, 98.71, 100.96, 102.58, 103.79, 105.17, 106.21, 107.38, 109.12, 109.92, 115.4, 121.5],
        'A': [68.90, 83.46, 86.29, 92.22, 95.64, 106.94, 118.78, 129.21, 134.76, 157.53, 163.96, 189.61, 191.78, 199.41, 201.03, 203.87, 205.46, 207.92, 214.55, 222.76, 326.7]}
PLAN = [  # out a, out b, mode, source, src start, params, slide into this piece
    (0.0, 6.3, 'BL', 'P:bard', 2.0, (), None),           # hook: ranks reset, Challenger falls to Iron IV
    (6.3, 11.8, 'G', 'P:azir', 2.0, (656,), 'L'),        # panik yok, gorunen derece, MMR
    (11.8, 16.82, 'G', 'P:galio', 2.0, (656,), 'R'),     # same level, climb together
    (16.82, 21.64, 'G', 'P:bard', 8.0, (656,), 'L'),     # LP
    (21.64, 27.94, 'BL', 'P:ezreal', 2.0, (), 'R'),      # Zamansiz Sanli
    (27.94, 32.72, 'CARD', 'A', 69.0, (), 'L'),          # Arakci
    (32.72, 35.34, 'CARD', 'A', 95.7, (), 'R'),          # Devdogan
    (35.34, 39.98, 'CARD', 'A', 164.0, (), 'L'),         # new items
    (39.98, 41.38, 'CARD', 'A', 208.0, (), 'R'),         # Peri Isiklari
    (41.38, 44.7, 'C', 'B', 66.2, (700, .15), 'L'),      # ARAM
    (44.7, END, 'BL', 'P:azir', 12.0, (), 'R'),          # outro
]
BLUR = 'gblur=sigma=24,eq=brightness=-0.08:saturation=1.15'
SOFT = 'gblur=sigma=11,eq=brightness=-0.1:saturation=1.1'

def path(src): return SRC[src] if src in SRC else f'{S}/patch/norm/{src[2:]}_gameplay.mp4'
def lim(src, ss):
    if src not in CUTS: return 999
    return min(c for c in CUTS[src] if c > ss + 0.05) - ss - 0.03

def vf(p):
    a, b, m, src, ss, q, tr = p
    pre = f'trim=end={lim(src, ss):.3f},'
    if m == 'G': return pre + f'crop=439:780:{q[0] + 84}:40,scale=1080:1920:flags=lanczos,' + SOFT
    if m == 'C': return pre + f'crop=506:900:{q[0]}:0,scale=1080:1920:flags=lanczos,' + SOFT
    if m == 'BL':
        c = 'crop=1102:620:89:0,scale=-2:1920,crop=1080:1920:(iw-1080)/2:0,' if src == 'A' else 'crop=439:780:740:40,scale=1080:1920,'
        return pre + c + BLUR
    if m == 'CARD':
        return (pre + 'crop=1102:620:89:0,split[a][b];[a]scale=-2:1920,crop=1080:1920:(iw-1080)/2:0,' + BLUR +
                f'[bg];[b]scale=1000:563:flags=lanczos[fg];[bg][fg]overlay=40:{CY}')

def seglen(i):
    nxt = PLAN[i + 1] if i + 1 < len(PLAN) else None
    return PLAN[i][1] - PLAN[i][0] + (D if nxt and nxt[6] else 0)

def base():
    vids = []
    for i, p in enumerate(PLAN):
        o = f'{OUT}/v{i:02d}.mp4'; vids.append(o)
        f = f'[0:v]{vf(p)},setpts=PTS-STARTPTS,fps=30,tpad=stop_mode=clone:stop_duration=3,setsar=1,format=yuv420p[v]'
        subprocess.run(['ffmpeg', '-v', 'error', '-y', '-ss', str(p[4]), '-i', path(p[3]), '-filter_complex', f, '-map', '[v]', '-frames:v', str(round(seglen(i) * 30)),
                        '-an', '-c:v', 'libx264', '-preset', 'veryfast', '-crf', '16', '-pix_fmt', 'yuv420p', o], check=True)
    inp = []
    for v in vids: inp += ['-i', v]
    fc = [f'[{i}:v]fps=30,setpts=PTS-STARTPTS,settb=AVTB[i{i}]' for i in range(len(vids))]; cur = '[i0]'
    for i in range(1, len(PLAN)):
        tr = PLAN[i][6]; lab = f'[x{i}]'
        if tr: fc.append(f"{cur}[i{i}]xfade=transition={'slideleft' if tr == 'L' else 'slideright'}:duration={D}:offset={PLAN[i][0]:.3f}{lab}")
        else: fc.append(f'{cur}[i{i}]concat=n=2:v=1:a=0,settb=AVTB{lab}')
        cur = lab
    subprocess.run(['ffmpeg', '-v', 'error', '-y'] + inp + ['-filter_complex', ';'.join(fc), '-map', cur, '-c:v', 'libx264', '-preset', 'veryfast', '-crf', '16', '-pix_fmt', 'yuv420p', f'{OUT}/base.mp4'], check=True)
    open('timeline.js', 'w').write('// generated by build.py\nconst PLAN=' + json.dumps([[p[0], p[1], p[2]] for p in PLAN]) + f';\nconst END={END},CY={CY};\n')
    print('base ok')

def mix():
    subprocess.run(['node', 'render.js', 'info'], check=True); ev = json.load(open('sfx.json'))
    G = {'impact': -15, 'stamp_dan': -10, 'yazi_vurus': -15, 'card': -17, 'pop': -19, 'click': -14, 'el_swoosh': -22, 'el_pop': -16, 'el_hit': -14, 'el_slot': -24, 'el_text': -22}
    inp = ['-i', '../ses/vo.mp3', '-stream_loop', '-1', '-i', '../../../sett/ses/muzik.mp3']
    fc = [f'[0]aresample=48000,aformat=channel_layouts=stereo,volume=4dB,apad=whole_dur={END},asplit[vo][sc]',
          f'[1]aresample=48000,aformat=channel_layouts=stereo,atrim=0:{END},volume=-15dB,afade=t=in:d=0.3,afade=t=out:st={END - 0.5}:d=0.5[m0]',
          '[m0][sc]sidechaincompress=threshold=0.02:ratio=6:attack=15:release=400[m]']; lab = ['[vo]', '[m]']
    for i, (n, t, g) in enumerate(ev):
        inp += ['-i', f'../ses/{n}.wav' if n.startswith('el_') else f'../../../ocak2027/ses/{n}.wav']
        fc.append(f'[{i + 2}]aresample=48000,aformat=channel_layouts=stereo,volume={G[n] + g}dB,adelay={int(t * 1000)}:all=1[s{i}]'); lab.append(f'[s{i}]')
    fc.append(''.join(lab) + f'amix=inputs={len(lab)}:normalize=0:duration=first,atrim=0:{END},loudnorm=I=-14:TP=-1.5:LRA=11[o]')
    subprocess.run(['ffmpeg', '-v', 'error', '-y'] + inp + ['-filter_complex', ';'.join(fc), '-map', '[o]', '-ar', '48000', f'{OUT}/mix.wav'], check=True)
    print('mix ok')

if __name__ == '__main__':
    {'base': base, 'mix': mix}[sys.argv[1]]()
